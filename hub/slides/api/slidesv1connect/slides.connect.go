// Slides (if-slides-api): render a slide deck from a structured description and fetch it again
// by its ID. One of the record types of the hub (dec-records-per-type).
//
// The hub keeps the input of every deck (title, slides, author, time) in its archive
// (dec-yaml-git-storage), so decks survive a restart. The rendered output is not stored: the hub
// renders it again from the input. Rendering is deterministic (con-no-intelligence): the same
// title and slides give the same bytes.
//
// A deck has an ID such as "slides/42". The stage shows a deck by this ID (artifact.focused in
// commands.proto): "artifact" is the general word for anything the stage can show, and the part
// before the slash names its type.
//
// Every call needs an access token of a participant (see identity.proto). A stage link cannot
// use this interface: the stage loads decks inside the hub. A sentence that is off the record
// must not go into a deck (dec-off-the-record).
//
// A deck that names a meeting session waits for the release of that session
// (concept-session-release): it is staged. Only a participant of the session may name it. Until
// the release, every participant of the session may change or remove a staged deck, and only the
// readers of the session (its participants and the tenant admins) and the stage of the session see
// its content. Everyone else sees its stub: a deck with only its id and stub set. A released deck,
// or a deck without a session, never changes through this interface.

