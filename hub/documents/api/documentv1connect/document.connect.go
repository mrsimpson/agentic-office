// Documents (if-document-api): create and change text documents. A text document is a Markdown
// file in the directory "documents" of the repository, without a schema (dec-artifacts). It is
// one type of artifact; read it through the archive (archive.proto).
//
// The path of a document is its identity: "documents/<name>.md", with subdirectories if you
// like. A change always applies to the head of the repository. It names the version that its
// author read; when the document has another version by then, the change fails with aborted
// and the message has the current version. The author reads the document again and tries
// again. Of two changes with the same base, the first one wins.
//
// Every call needs an access token of a participant (see identity.proto). The archive records
// the participant as the author of the commit. A call may name a session: the hub then appends
// artifact.created or artifact.changed to the log of that session, and the participant must
// have joined it. A sentence that is off the record must not go into a document
// (dec-off-the-record); the hub does not check this.
//
// A new document that names a session waits for the release of that session
// (concept-session-release): it is staged. It lies in the staging area of the session, and the
// repository holds its stub at the same path: the same Markdown text for every staged document,
// whose front matter names the schema office.document.v1 and "stub: true". Until the release,
// every participant of the session may change or remove a staged document, and each change must
// name that session. Read a staged document through the archive (archive.proto): only the readers
// of the session see its content. A change of a released document is not held, whatever session
// it names. No call changes a stub, and no call writes the content of a stub.
//
// A document may name the schema office.document.v1 in the field "schema" of its front matter
// (dec-wiki). Then the hub checks the other fields of the front matter, all optional: title and
// summary (one line each), tags (a list), sources (a list of paths of records from the top of the
// repository, for example minutes/000012.yaml), status (draft, reviewed or outdated), owner (a
// participant ID) and reviewed (a list of reviews, each with the fields id, a participant ID, and
// date, YYYY-MM-DD). Any other field is invalid. A create or a change with invalid front matter, or
// with front matter that names another schema, fails with invalid_argument and the reasons. A
// document without front matter is valid; its first heading is its title.
//
// A create or a change answers with a hint for every relative Markdown link of the document that
// leads to no file of the repository. A stub counts as a file. A hint never refuses the write.

