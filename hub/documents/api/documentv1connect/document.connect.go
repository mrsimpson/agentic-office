// Documents (if-document-api): create and change text documents. A text document is a Markdown
// file in the directory "documents" of the repository, without a schema (dec-artifacts). It is
// one type of artifact; read it through the archive (archive.proto).
//
// The path of a document is its identity: "documents/<name>.md", with subdirectories if you
// like. A change always applies to the head of the repository. It names the version that its
// author read; when the document has another version by then, the change fails with aborted
// and the message has the current version. The author reads the document again and tries
// again. Of two changes with the same base, the first one wins.
//
// Every call needs an access token of a participant (see identity.proto). The archive records
// the participant as the author of the commit. A call may name a session: the hub then appends
// artifact.created or artifact.changed to the log of that session, and the participant must
// have joined it. A sentence that is off the record must not go into a document
// (dec-off-the-record); the hub does not check this.

