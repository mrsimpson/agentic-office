// Tasks (if-task-api): work items of the team, with a title, a description, an assignee, a status
// and an optional link to a meeting session. One of the record types of the hub
// (dec-records-per-type).
//
// For now every task is a local draft that the hub stores in its archive (dec-yaml-git-storage).
// Later the hub syncs tasks with the task tool of the team (for example GitHub or GitLab issues),
// and the synced task replaces the draft (#40). The contract is made for that step:
//
//   - A task is named by its ref, a string with a scheme, for example "local:42" today and
//     "github:owner/repo#12" later. Clients must treat a ref as opaque: they store it and pass it
//     back, and never build or parse one.
//   - source tells where the task lives. Today it is always TASK_SOURCE_LOCAL.
//   - The list call pages with an opaque page token, not with a number.
//
// Every call needs an access token of a participant (see identity.proto). A stage link cannot
// read or write tasks. A sentence that is off the record must not go into a task
// (dec-off-the-record).

