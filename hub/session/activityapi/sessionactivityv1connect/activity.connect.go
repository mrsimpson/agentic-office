// Session activity (if-session-activity): what a participant is doing right now, for example
// that an agent works and which tool it calls (dec-agent-activity).
//
// The activity is short-lived. It is not an event of the session log: the hub keeps only the
// latest activity of each participant, in memory, and never stores, archives or replicates it.
//
// - ReportActivity sets the activity of the caller. A report lives for ttl (see
//   ReportActivityResponse); a participant that keeps an activity renews it before then. A new
//   report replaces the old one. The activity of a participant ends when it expires, when the
//   participant leaves, and for everybody when the session ends.
// - WatchActivity sends the current activities of a session at once, then again after every
//   change, until the caller goes away or the session ends.
//
// The activity names a tool by a short name only (a lowercase word with letters, digits and
// underscores), never by its arguments: those can carry sentences that are off the record.
//
// Every call needs an access token (see identity.proto). ReportActivity needs a participant token:
// participant_id must be the participant of the token, who must have joined the session and not
// left it; a stage link cannot report. WatchActivity takes a participant token of the tenant or a
// stage link for this session.
//
// Error codes: a missing or wrong field is invalid_argument; a participant_id that is not the
// caller, a stage link that reports or watches another session, are permission_denied; a report
// for a session that has ended, or of a participant that has not joined it or has left, is
// failed_precondition.

