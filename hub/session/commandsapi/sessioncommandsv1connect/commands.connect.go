// Session commands (if-session-commands): the synchronous calls of a participant in a meeting
// session, the checks of a session log, and the offer of a copy after the hub lost events.
//
// Every command carries a command_id that the client creates: unique and sortable by time, for
// example a UUIDv7 (dec-idempotent-commands). If the same command_id arrives again, the server
