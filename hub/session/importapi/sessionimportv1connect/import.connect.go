// Session import (if-session-import): imports a whole conversation that happened outside the
// office as a new session (dec-session-import).
//
// A conversation comes in one call or in pages. Every page is one ImportConversation call with its
// own command_id that the client creates (dec-idempotent-commands). If the same command_id
// arrives again, the hub returns the stored result of that page with duplicate set and stores
// nothing new. Pages are applied in the order they arrive.
//
// - The first page creates the session. The session must have no events yet. The first page sets
//   conversation; later pages must not. The hub writes session.imported as event 1.
// - Every page may add participants and utterances. A participant is written as participant.joined
//   with imported set and the participant ID "imported:" + key. An utterance is written as
//   utterance.final of that participant, in the order of the page, with original_time if given.
//   An utterance may only name a participant of the same or an earlier page.
// - The page with complete set writes import.completed after its own events. It ends the import.
// - Until the import is complete, the session takes only pages of the participant who sent the
//   first page; every session command fails with failed_precondition. After it, the session takes
//   no more pages, and takes session commands like any other session.
//
// The events of a page all carry the command_id of the page, and the importer as
// actor_participant_id. Every call needs an access token of a participant (see identity.proto);
// participant_id must be that participant. A stage link cannot import.
//
// Error codes: a missing or wrong field is invalid_argument; a first page for a session that has
// events, a page for a session that is not being imported, a page after the import is complete, a
// page for a session of another schema, are failed_precondition; a page of another participant
// than the importer, or a participant_id that is not the caller, is permission_denied; a
// command_id that was used for another command is already_exists.

