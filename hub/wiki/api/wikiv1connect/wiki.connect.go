// Wiki (if-wiki-api): the derived view of the wiki of a tenant (concept-wiki, dec-wiki). The
// portal shows it; it has no logic of its own (dec-web-portal).
//
// All artifacts of a tenant form its wiki. The hub follows the artifact repository of the tenant
// and keeps a view of it: the index of the artifacts, the links and backlinks of each artifact,
// the links that lead nowhere, the sources that no document cites yet (the ingest queue), and a
// search by words. The part that owns a type describes its files (title, summary, tags, links,
// sources); this interface only shows what they describe. The view is read only: it writes
// nothing, and the hub builds it again from the repository at start.
//
// What the view holds:
//
//   - Only released artifacts. The view never reads the staging area. The stub of a staged
//     artifact (concept-session-release) is not in the index, the search or the queue, but a link
//     to a stub leads somewhere: the file is there.
//   - Every path is relative to the top of the repository, with slashes, for example
//     "notes/000003.md".
//   - A link leads somewhere when its path is a file of the repository or a directory with files.
//   - A source is a decision, minutes or a note. A document cites it in the field sources of its
//     front matter.
//   - A file that the hub cannot describe, for example one that is not valid, is not in the view.
//
// The view follows each change of the repository, from a write through an interface of the hub
// or from a push. It may show a change a moment after the write returned.
//
// Every call needs an access token of a member of the tenant (see identity.proto), and every
// member reads the whole view: every member may read every released artifact. A stage link cannot
// use this interface (permission_denied). Agents read their clone with their own tools; the CLI
// and the MCP server have no access to this interface.

