// User API (if-user-api): the users of the hub, their keys, their memberships in tenants and the
// system admins (concept-multi-tenancy, dec-multi-tenancy).
//
// Two steps: a system admin registers a user (CreateUser), then a system admin or the tenant admin
// assigns the user to a tenant (SetMembership). Identity is the only writer of this data. It
// refuses a change that would break one of these rules with failed_precondition:
//
//   - every active user has at least one key that is not revoked;
//   - a key belongs to one user, also after it was revoked;
//   - at least one system admin is active, and a system admin is a human;
//   - a system admin is never a member of a tenant;
//   - an active membership belongs to an active user;
//   - a tenant with an active member has an active tenant admin.
//
// Users and memberships have a validity period. Removing one ends the period and keeps the
// record, so a user ID is never used again.
//
// Every call needs an access token (see identity.proto). Every command carries a command_id that
// the client creates (dec-idempotent-commands). A call that the token does not allow fails with
// permission_denied.

