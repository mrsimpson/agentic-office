// Decisions (if-decision-api): what the team decided, with who decided it. One of the record
// types of the hub (dec-records-per-type). The hub stores every decision in the archive.
//
// Every call needs an access token of a participant (see identity.proto). A stage link cannot
// read or write decisions. A sentence that is off the record must not go into a decision
// (dec-off-the-record).
//
// A decision that names a meeting session waits for the release of that session
// (concept-session-release): it is staged. Only a participant of the session may name it. Until
// the release, every participant of the session may change or remove a staged decision, and only
// the readers of the session (its participants and the tenant admins) see its content. Everyone
// else sees its stub: a decision with only its id and stub set. A released decision, or a
// decision without a session, never changes.

