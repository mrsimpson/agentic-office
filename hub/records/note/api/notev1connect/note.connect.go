// Notes (if-note-api): free notes of a participant, with or without a meeting session. One of the
// record types of the hub (dec-records-per-type). The hub stores every note in the archive as a
// Markdown file: the text is the body, and the other fields are its front matter (dec-wiki).
//
// Every call needs an access token of a participant (see identity.proto). A stage link cannot
// read or write notes. A sentence that is off the record must not go into a note
// (dec-off-the-record).
//
// A note that names a meeting session waits for the release of that session
// (concept-session-release): it is staged. Only a participant of the session may name it. Until
// the release, every participant of the session may change or remove a staged note, and only the
// readers of the session (its participants and the tenant admins) see its content. Everyone else
// sees its stub: a note with only its id and stub set. A released note, or a note without a
// session, never changes.

